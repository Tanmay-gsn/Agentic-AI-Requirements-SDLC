/**
 * Software Requirements Specification (SRS) & SDLC Blueprint Exporter
 * Generates an IEEE 830 compliant markdown document.
 */

export function generateSRSMarkdown(scenarioTitle, scenarioText, requirementResult, sdlcResult) {
  const { functionalRequirements = [], nonFunctionalRequirements = [], qualityReport = {}, traceabilityMatrix = [] } = requirementResult;
  const { primaryModel = {}, rankedRecommendations = [], projectWorkflow = [] } = sdlcResult;

  return `# SOFTWARE REQUIREMENTS SPECIFICATION (SRS) & SDLC BLUEPRINT
**System Title:** ${scenarioTitle || 'Software Module Specification'}
**Generated By:** Agentic-AI Requirements & SDLC Synthesizer
**Date:** ${new Date().toLocaleDateString()} | **Status:** Formal Draft (Human Review Pending)

---

## 1. INTRODUCTION & SCOPE
### 1.1 Purpose
This document specifies the software requirements and life-cycle development plan for the module described as follows:
> "${scenarioText.trim()}"

### 1.2 System Domain & Classification
- **Domain:** ${requirementResult.domain || 'Financial / Enterprise Technology'}
- **Identified Regulations:** ${(requirementResult.metrics?.regulatoryStandardsMapped || []).join(', ') || 'Enterprise Standard'}
- **Quality Score:** ${qualityReport.overallScore || 90}/100

---

## 2. FUNCTIONAL REQUIREMENTS (Agent 1 Output)

${functionalRequirements.map((fr, idx) => `
### 2.${idx + 1} [${fr.id}] ${fr.title}
- **Category:** ${fr.category}
- **Priority:** ${fr.priority} | **Risk Level:** ${fr.riskLevel}
- **Source Stakeholder:** ${fr.sourceStakeholder}
- **Requirement Statement:**
  ${fr.statement}
- **User Story:**
  *${fr.userStory}*
- **Acceptance Criteria:**
${fr.acceptanceCriteria.map(ac => `  - ${ac}`).join('\n')}
- **Business Justification:** ${fr.businessJustification}
- **Applicable Regulations:** ${fr.applicableRegulations ? fr.applicableRegulations.join(', ') : 'N/A'}
`).join('\n')}

---

## 3. NON-FUNCTIONAL REQUIREMENTS (Agent 1 Output)

${nonFunctionalRequirements.map((nfr, idx) => `
### 3.${idx + 1} [${nfr.id}] ${nfr.title}
- **Category:** ${nfr.category} | **Priority:** ${nfr.priority}
- **Specification Statement:** ${nfr.statement}
- **Verifiable Target Metrics:** ${nfr.targetMetrics}
- **Regulatory Framework:** ${nfr.applicableRegulations ? nfr.applicableRegulations.join(', ') : 'Standard'}
`).join('\n')}

---

## 4. QUALITY & AMBIGUITY AUDIT

- **Overall Quality Rating:** ${qualityReport.overallScore}/100 (${qualityReport.status})
- **Testability Rating:** ${qualityReport.testabilityRating}
- **Ambiguities Detected:** ${qualityReport.ambiguities?.length || 0}
${(qualityReport.ambiguities || []).map(a => `  - **Term "${a.term}":** ${a.finding} -> *Recommendation:* ${a.recommendation}`).join('\n')}

---

## 5. REQUIREMENTS TRACEABILITY MATRIX (RTM)

| Req ID | Requirement Title | Category | Stakeholder | Regulatory Mapping | Verification Gate |
|---|---|---|---|---|---|
${traceabilityMatrix.map(t => `| **${t.requirementId}** | ${t.title} | ${t.type} | ${t.stakeholder} | ${t.regulatoryMapping} | ${t.verificationStage} |`).join('\n')}

---

## 6. SDLC SELECTION & JUSTIFICATION (Agent 2 Output)

### 6.1 Multi-Criteria Decision Analysis (MCDA) Ranking
${rankedRecommendations.map((r, i) => `${i + 1}. **${r.name}** — **${r.suitabilityScore}% Match**\n   *Rationale:* ${r.rationale}`).join('\n')}

### 6.2 Recommended Primary Life Cycle: ${primaryModel.name} (${primaryModel.suitabilityScore}% Match)
**Justification:** ${primaryModel.rationale}

---

## 7. PROJECT-SPECIFIC SDLC WORKFLOW

${projectWorkflow.map(phase => `
### Phase ${phase.phaseNumber}: ${phase.phaseName}
- **Duration Estimate:** ${phase.durationEstimate}
- **Phase Objective:** ${phase.objective}
- **Responsible Roles:** ${phase.responsibleRoles.join(', ')}
- **Key Activities:**
${phase.activities.map(act => `  - ${act}`).join('\n')}
- **Expected Deliverables:**
${phase.deliverables.map(del => `  - ${del}`).join('\n')}
- **Security Activities & Controls:**
${phase.securityControls.map(sec => `  - [SEC] ${sec}`).join('\n')}
- **Compliance Checkpoint & Gate:** ${phase.complianceCheckpoints}
- **Entry Criteria:** ${phase.entryCriteria}
- **Exit Criteria:** ${phase.exitCriteria}
`).join('\n')}

---

## 8. HUMAN-IN-THE-LOOP APPROVAL SIGN-OFF
- **Lead Software Architect Sign-Off:** ____________________  Date: ________
- **Chief Information Security Officer (CISO):** ___________  Date: ________
- **Chief Compliance Officer (CCO):** _____________________  Date: ________
`;
}
